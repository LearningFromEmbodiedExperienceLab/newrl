#!/bin/sh
# Install zsh completion for config presets, such as task=anymal_loco_flat.
# Re-run after adding a preset. Then open a new shell or source ~/.zshrc.

set -eu

root=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
zshrc=${ZSHRC:-"$HOME/.zshrc"}
dest=${NEWRL_COMPLETION:-"$HOME/.local/share/newrl/newrl-completion.zsh"}
export NEWRL_COMPLETION="$dest"

mkdir -p "$(dirname "$dest")"
cd "$root"
if [ -n "${VIRTUAL_ENV:-}" ]; then
  set -- python
else
  set -- uv run python
fi
"$@" - <<'PY'
import os

import newrl.algos.ppo  # noqa: F401
import newrl.configs  # noqa: F401
from newrl.utils.config import cs

lines = [
    "# Generated by scripts/install_zsh_completion.sh. Re-run that script to refresh.",
    "typeset -A _newrl_presets",
]
for group in cs.groups():
    names = cs.names(group)
    if names:
        lines.append(f'_newrl_presets[{group}]="{" ".join(names)}"')
lines.append(
    r"""
_newrl_preset() {
    # The value prefix is already typed: task=an -> task=anymal_loco_flat.
    [[ $PREFIX == *=?* ]] || return 1
    local group=${PREFIX%%=*}
    (( ${+_newrl_presets[$group]} )) || return 1
    compset -P '*=' || return 1
    local -a options
    options=(${=_newrl_presets[$group]})
    compadd -S '' -- $options
}

autoload -Uz compinit
(( ${+functions[_complete]} )) || compinit
() {
    local -a completers
    zstyle -a ':completion:*' completer completers
    (( ${completers[(I)_newrl_preset]} )) || \
        zstyle ':completion:*' completer _newrl_preset ${completers:-_complete}
}
"""
)
with open(os.environ["NEWRL_COMPLETION"], "w") as handle:
    handle.write("\n".join(lines) + "\n")
PY

marker="# newrl-completion"
quoted=$(printf "%s" "$dest" | sed "s/'/'\\\\''/g")
source_line="$marker
source '$quoted'"
if [ -f "$zshrc" ] && grep -q "$marker" "$zshrc"; then
    echo "Already installed in $zshrc"
else
    touch "$zshrc"
    printf '\n%s\n' "$source_line" >> "$zshrc"
    echo "Added completion to $zshrc"
fi
echo "Wrote $dest"
echo "Open a new zsh, or run: source '$zshrc'"
