"""Compile NewRL's command tree and config schemas into a zsh completion table."""

from argparse import ArgumentParser, _SubParsersAction
from collections import defaultdict
from dataclasses import MISSING, fields, is_dataclass
from importlib import import_module
from pathlib import Path
from shlex import quote
from types import NoneType, UnionType
from typing import Literal, Union, get_args, get_origin, get_type_hints

from newrl.cli import build_parser
from newrl.projects import load_projects
from newrl.utils.config import cs


def config_completions(schema):
    keys, values = {"config_out"}, defaultdict(set)

    def visit(node, prefix, ancestors):
        cls = node if isinstance(node, type) else type(node)
        if not is_dataclass(cls) or cls in ancestors:
            return
        hints = get_type_hints(cls)
        for field in fields(cls):
            if not field.init or field.metadata.get("runtime"):
                continue
            path = prefix + field.name
            keys.add(path)
            hint = hints.get(field.name)
            choices = get_args(hint) if get_origin(hint) in (Union, UnionType) else (hint,)
            known_types = tuple(choice for choice in choices if is_dataclass(choice))
            children = set(known_types)

            group = field.metadata.get("preset_group")
            if group is None:
                for choice in choices:
                    if choice is bool:
                        values[path].update(("true", "false"))
                    elif choice is NoneType:
                        values[path].add("none")
                    elif get_origin(choice) is Literal:
                        values[path].update(str(option) for option in get_args(choice))
                suffix = path
                while suffix and not cs.names(suffix):
                    _, _, suffix = suffix.partition(".")
                group = suffix
            for name, preset in cs.definitions(group).items():
                preset_cls = preset if isinstance(preset, type) else type(preset)
                if known_types and not issubclass(preset_cls, known_types):
                    continue
                values[path].add(name)
                visit(preset, path + ".", ancestors | {cls})

            sample = getattr(node, field.name, MISSING) if not isinstance(node, type) else field.default
            if is_dataclass(sample):
                visit(sample, path + ".", ancestors | {cls})
            if is_dataclass(field.default_factory):
                children.add(field.default_factory)
            for child in children:
                visit(child, path + ".", ancestors | {cls})

    visit(schema, "", set())
    return keys, values


def render(parser: ArgumentParser) -> str:
    lines = [
        "# Generated by scripts/install_zsh_completion.sh.",
        "typeset -gA _newrl_commands=() _newrl_flags=() _newrl_keys=() _newrl_values=()",
    ]

    def row(table, key, options):
        if options:
            lines.append(f"{table}[{quote(key)}]={quote(' '.join(sorted(options)))}")

    def visit(command, path):
        row("_newrl_flags", path, {option for action in command._actions for option in action.option_strings})
        for action in command._actions:
            if isinstance(action, _SubParsersAction):
                row("_newrl_commands", path, action.choices)
                for name, child in action.choices.items():
                    visit(child, f"{path}:{name}")
        module = command.get_default("config_command")
        if module:
            schema = getattr(import_module(module), command.get_default("config_schema"))
            keys, values = config_completions(schema)
            row("_newrl_keys", path, keys)
            for key, options in sorted(values.items()):
                row("_newrl_values", f"{path}:{key}", options)

    # Load each command's registrations before collecting any preset choices.
    def load_commands(command):
        if module := command.get_default("config_command"):
            import_module(module)
        for action in command._actions:
            if isinstance(action, _SubParsersAction):
                for child in action.choices.values():
                    load_commands(child)

    load_commands(parser)
    load_projects()
    visit(parser, "newrl")
    return "\n".join(lines) + "\n" + Path(__file__).with_name("newrl-completion.zsh").read_text()


if __name__ == "__main__":
    print(render(build_parser()), end="")
